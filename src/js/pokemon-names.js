function normalizeName(value) {
 return String(value).trim().toLowerCase().replaceAll("♀","f").replaceAll("♂","m").normalize("NFD").replace(/[\u0300-\u036f]/g,"").replace(/[^a-z0-9]/g,"");
}
const byId = new Map(POKEMON_NAMES.map(entry=>[entry.id,entry]));
const byName = new Map(POKEMON_NAMES.flatMap(entry=>[[normalizeName(entry.english),entry],[normalizeName(entry.french),entry]]));
export function pokemonName(pokemon, fallbackId) {
 const id=typeof pokemon==="object"&&pokemon!==null ? pokemon.id : typeof pokemon==="number" ? pokemon : fallbackId;
 const value=typeof pokemon==="object"&&pokemon!==null ? pokemon.name : pokemon;
 return (byId.get(Number(id))??byName.get(normalizeName(value??"")))?.french ?? (value ? String(value).replaceAll("-"," ") : `Pokémon n° ${fallbackId??id??"?"}`);
}
export function pokemonApiQuery(query) {
 const value=String(query).trim();
 return byName.get(normalizeName(value))?.english ?? value.toLowerCase();
}
export function matchesPokemonName(query,pokemon,id) {
 const entry=byId.get(Number(pokemon?.id??id));
 const value=normalizeName(query);
 return !value || [entry?.french,entry?.english,pokemon?.name,String(pokemon?.id??id)].some(name=>name!=null&&normalizeName(name).includes(value));
}
